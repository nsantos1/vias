-- =====================================================================
-- VIAS - Via Inteligente de Acesso a Saude
-- Esquema PROVISORIO da API (Oracle 19c ou superior), seguindo o nucleo de
-- quatro tabelas do alinhamento tecnico (REGIAO, UNIDADE_SAUDE, SERVICO_SAUDE,
-- UNIDADE_SERVICO) + FONTE_DADO para a proveniencia.
-- Deve ser substituido/ajustado pelo schema aprovado pela frente Oracle (Nicolas).
-- Booleanos em CHAR(1) 'S'/'N'. Estados desconhecidos sao explicitos, nunca "N" por padrao.
-- =====================================================================

CREATE TABLE FONTE_DADO (
    id_fonte      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    sigla         VARCHAR2(30)  NOT NULL,
    nome          VARCHAR2(150) NOT NULL,
    url           VARCHAR2(300),
    oficial       CHAR(1) NOT NULL,
    CONSTRAINT pk_fonte_dado PRIMARY KEY (id_fonte),
    CONSTRAINT uk_fonte_dado_sigla UNIQUE (sigla),
    CONSTRAINT ck_fonte_dado_oficial CHECK (oficial IN ('S','N'))
);

CREATE TABLE REGIAO (
    id_regiao         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nome              VARCHAR2(100) NOT NULL,
    tipo_regiao       VARCHAR2(25)  NOT NULL,
    codigo_municipio  VARCHAR2(7)   NOT NULL,
    uf                CHAR(2)       NOT NULL,
    id_fonte          NUMBER(10)    NOT NULL,
    CONSTRAINT pk_regiao PRIMARY KEY (id_regiao),
    CONSTRAINT uk_regiao UNIQUE (nome, tipo_regiao, codigo_municipio),
    CONSTRAINT ck_regiao_tipo CHECK (tipo_regiao IN ('MUNICIPIO','DISTRITO','BAIRRO','REGIAO_ADMINISTRATIVA')),
    CONSTRAINT fk_regiao_fonte FOREIGN KEY (id_fonte) REFERENCES FONTE_DADO (id_fonte)
);

CREATE TABLE UNIDADE_SAUDE (
    id_unidade                      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    codigo_cnes                     VARCHAR2(7),
    nome                            VARCHAR2(150) NOT NULL,
    razao_social                    VARCHAR2(150),
    codigo_tipo_unidade             NUMBER(3),
    tipo_unidade                    VARCHAR2(120),
    logradouro                      VARCHAR2(150),
    numero                          VARCHAR2(10),
    bairro                          VARCHAR2(80),
    cep                             VARCHAR2(8),
    codigo_municipio                VARCHAR2(7),
    uf                              CHAR(2),
    telefone                        VARCHAR2(30),
    latitude                        NUMBER(10,7),
    longitude                       NUMBER(10,7),
    horario_funcionamento           VARCHAR2(120),
    atende_sus                      VARCHAR2(15) DEFAULT 'NAO_INFORMADO' NOT NULL,
    status_acessibilidade           VARCHAR2(15) DEFAULT 'NAO_INFORMADO' NOT NULL,
    fonte_acessibilidade            VARCHAR2(200),
    data_verificacao_acessibilidade DATE,
    id_regiao                       NUMBER(10),
    id_fonte                        NUMBER(10) NOT NULL,
    data_referencia_fonte           DATE,
    data_carga                      TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    data_atualizacao                TIMESTAMP,
    CONSTRAINT pk_unidade_saude PRIMARY KEY (id_unidade),
    CONSTRAINT uk_unidade_cnes UNIQUE (codigo_cnes),
    CONSTRAINT ck_unidade_cnes CHECK (codigo_cnes IS NULL OR REGEXP_LIKE(codigo_cnes, '^[0-9]{7}$')),
    CONSTRAINT ck_unidade_sus CHECK (atende_sus IN ('SIM','NAO','NAO_INFORMADO')),
    CONSTRAINT ck_unidade_acess CHECK (status_acessibilidade IN ('ACESSIVEL','NAO_ACESSIVEL','NAO_INFORMADO','NAO_VERIFICADO')),
    -- ACESSIVEL / NAO_ACESSIVEL so com fonte e data de verificacao
    CONSTRAINT ck_unidade_acess_fonte CHECK (status_acessibilidade IN ('NAO_INFORMADO','NAO_VERIFICADO')
        OR (fonte_acessibilidade IS NOT NULL AND data_verificacao_acessibilidade IS NOT NULL)),
    CONSTRAINT ck_unidade_lat CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_unidade_lon CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_unidade_coord CHECK ((latitude IS NULL AND longitude IS NULL) OR (latitude IS NOT NULL AND longitude IS NOT NULL)),
    CONSTRAINT fk_unidade_regiao FOREIGN KEY (id_regiao) REFERENCES REGIAO (id_regiao),
    CONSTRAINT fk_unidade_fonte FOREIGN KEY (id_fonte) REFERENCES FONTE_DADO (id_fonte)
);

CREATE INDEX ix_unidade_regiao ON UNIDADE_SAUDE (id_regiao);
CREATE INDEX ix_unidade_tipo ON UNIDADE_SAUDE (codigo_tipo_unidade);

CREATE TABLE SERVICO_SAUDE (
    id_servico     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    codigo         VARCHAR2(40)  NOT NULL,
    nome           VARCHAR2(100) NOT NULL,
    descricao      VARCHAR2(300),
    campo_origem   VARCHAR2(80),
    id_fonte       NUMBER(10)    NOT NULL,
    CONSTRAINT pk_servico_saude PRIMARY KEY (id_servico),
    CONSTRAINT uk_servico_codigo UNIQUE (codigo),
    CONSTRAINT fk_servico_fonte FOREIGN KEY (id_fonte) REFERENCES FONTE_DADO (id_fonte)
);

-- Vinculo cadastral entre unidade e servico. NAO significa vaga, agenda ou atendimento hoje.
CREATE TABLE UNIDADE_SERVICO (
    id_unidade_servico     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_unidade             NUMBER(10) NOT NULL,
    id_servico             NUMBER(10) NOT NULL,
    id_fonte               NUMBER(10) NOT NULL,
    data_referencia_fonte  DATE,
    CONSTRAINT pk_unidade_servico PRIMARY KEY (id_unidade_servico),
    CONSTRAINT uk_unidade_servico UNIQUE (id_unidade, id_servico),
    CONSTRAINT fk_us_unidade FOREIGN KEY (id_unidade) REFERENCES UNIDADE_SAUDE (id_unidade) ON DELETE CASCADE,
    CONSTRAINT fk_us_servico FOREIGN KEY (id_servico) REFERENCES SERVICO_SAUDE (id_servico),
    CONSTRAINT fk_us_fonte FOREIGN KEY (id_fonte) REFERENCES FONTE_DADO (id_fonte)
);

CREATE INDEX ix_us_servico ON UNIDADE_SERVICO (id_servico);
