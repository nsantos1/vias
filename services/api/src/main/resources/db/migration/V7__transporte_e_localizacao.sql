-- ===== 2. Linhas de transporte (routes.txt do GTFS)
CREATE TABLE linha_transporte (
  id_linha                         NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo_gtfs                      VARCHAR2(20)  NOT NULL,
  nome                             VARCHAR2(150),
  modo                             VARCHAR2(10)  NOT NULL,
  status_acessibilidade            VARCHAR2(15)  DEFAULT 'NAO_INFORMADO' NOT NULL,
  fonte_acessibilidade             VARCHAR2(200),
  data_verificacao_acessibilidade  DATE,
  id_fonte                         NUMBER(10,0)  NOT NULL,
  data_referencia_fonte            DATE,
  data_carga                       TIMESTAMP(6)  DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-03:00' AS TIMESTAMP) NOT NULL,
  data_atualizacao                 TIMESTAMP(6),
  CONSTRAINT pk_linha_transporte PRIMARY KEY (id_linha),
  CONSTRAINT uk_linha_codigo_gtfs UNIQUE (codigo_gtfs),
  CONSTRAINT ck_linha_modo CHECK (modo IN ('ONIBUS', 'METRO', 'TREM')),
  CONSTRAINT ck_linha_acess CHECK (status_acessibilidade IN ('ACESSIVEL', 'NAO_ACESSIVEL', 'NAO_INFORMADO', 'NAO_VERIFICADO')),
  CONSTRAINT ck_linha_acess_fonte CHECK (status_acessibilidade IN ('NAO_INFORMADO', 'NAO_VERIFICADO')
      OR (fonte_acessibilidade IS NOT NULL AND data_verificacao_acessibilidade IS NOT NULL)),
  CONSTRAINT fk_linha_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_dado (id_fonte)
);

-- ===== 3. Paradas e estações (stops.txt do GTFS)
CREATE TABLE parada_transporte (
  id_parada                        NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  codigo_gtfs                      VARCHAR2(20)  NOT NULL,
  nome                             VARCHAR2(150) NOT NULL,
  descricao                        VARCHAR2(500),
  tipo_parada                      VARCHAR2(10)  DEFAULT 'PARADA' NOT NULL,
  latitude                         NUMBER(10,7)  NOT NULL,
  longitude                        NUMBER(10,7)  NOT NULL,
  localizacao                      SDO_GEOMETRY,
  status_acessibilidade            VARCHAR2(15)  DEFAULT 'NAO_INFORMADO' NOT NULL,
  fonte_acessibilidade             VARCHAR2(200),
  data_verificacao_acessibilidade  DATE,
  id_fonte                         NUMBER(10,0)  NOT NULL,
  data_referencia_fonte            DATE,
  data_carga                       TIMESTAMP(6)  DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-03:00' AS TIMESTAMP) NOT NULL,
  data_atualizacao                 TIMESTAMP(6),
  CONSTRAINT pk_parada_transporte PRIMARY KEY (id_parada),
  CONSTRAINT uk_parada_codigo_gtfs UNIQUE (codigo_gtfs),
  CONSTRAINT ck_parada_tipo CHECK (tipo_parada IN ('PARADA', 'ESTACAO')),
  CONSTRAINT ck_parada_lat CHECK (latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_parada_lon CHECK (longitude BETWEEN -180 AND 180),
  CONSTRAINT ck_parada_acess CHECK (status_acessibilidade IN ('ACESSIVEL', 'NAO_ACESSIVEL', 'NAO_INFORMADO', 'NAO_VERIFICADO')),
  CONSTRAINT ck_parada_acess_fonte CHECK (status_acessibilidade IN ('NAO_INFORMADO', 'NAO_VERIFICADO')
      OR (fonte_acessibilidade IS NOT NULL AND data_verificacao_acessibilidade IS NOT NULL)),
  CONSTRAINT fk_parada_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_dado (id_fonte)
);

-- ===== 4. Intervalo entre veículos (frequencies.txt + trips.txt do GTFS)
-- Horários em segundos desde 0h, porque o GTFS passa de 24h (24:40 = 0h40 do dia seguinte).
CREATE TABLE linha_intervalo (
  id_linha_intervalo  NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_linha            NUMBER(10,0) NOT NULL,
  sentido             NUMBER(1,0)  NOT NULL,
  codigo_calendario   VARCHAR2(20) NOT NULL,
  inicio_segundos     NUMBER(6,0)  NOT NULL,
  fim_segundos        NUMBER(6,0)  NOT NULL,
  intervalo_segundos  NUMBER(5,0)  NOT NULL,
  id_fonte            NUMBER(10,0) NOT NULL,
  data_referencia_fonte DATE,
  CONSTRAINT pk_linha_intervalo PRIMARY KEY (id_linha_intervalo),
  CONSTRAINT uk_linha_intervalo UNIQUE (id_linha, sentido, codigo_calendario, inicio_segundos),
  CONSTRAINT ck_intervalo_sentido CHECK (sentido IN (0, 1)),
  CONSTRAINT ck_intervalo_faixa CHECK (fim_segundos > inicio_segundos),
  CONSTRAINT ck_intervalo_positivo CHECK (intervalo_segundos > 0),
  CONSTRAINT fk_intervalo_linha FOREIGN KEY (id_linha) REFERENCES linha_transporte (id_linha) ON DELETE CASCADE,
  CONSTRAINT fk_intervalo_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_dado (id_fonte)
);

-- ===== 5. Histórico de previsões da Olho Vivo (atraso real no pior cenário)
-- ID_PARADA e ID_LINHA ficam opcionais até confirmarmos a ligação entre os códigos da
-- Olho Vivo (cp, letreiro) e os do GTFS (stop_id, route_id).
CREATE TABLE previsao_historico (
  id_previsao              NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  coletado_em              TIMESTAMP(6) NOT NULL,
  codigo_parada_olho_vivo  NUMBER(10,0) NOT NULL,
  id_parada                NUMBER(10,0),
  letreiro                 VARCHAR2(20) NOT NULL,
  id_linha                 NUMBER(10,0),
  prefixo_veiculo          VARCHAR2(10),
  chegada_prevista         TIMESTAMP(6) NOT NULL,
  veiculo_acessivel        VARCHAR2(15) DEFAULT 'NAO_INFORMADO' NOT NULL,
  id_fonte                 NUMBER(10,0) NOT NULL,
  CONSTRAINT pk_previsao_historico PRIMARY KEY (id_previsao),
  CONSTRAINT ck_previsao_acessivel CHECK (veiculo_acessivel IN ('SIM', 'NAO', 'NAO_INFORMADO')),
  CONSTRAINT fk_previsao_parada FOREIGN KEY (id_parada) REFERENCES parada_transporte (id_parada) ON DELETE SET NULL,
  CONSTRAINT fk_previsao_linha FOREIGN KEY (id_linha) REFERENCES linha_transporte (id_linha) ON DELETE SET NULL,
  CONSTRAINT fk_previsao_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_dado (id_fonte)
);

CREATE INDEX ix_previsao_letreiro_data ON previsao_historico (letreiro, coletado_em);

-- ===== 6. Localização espacial das unidades de saúde
-- LOCALIZACAO é preenchida por gatilho a partir de LATITUDE e LONGITUDE,
-- então quem carrega os dados não precisa mudar nada.
ALTER TABLE unidade_saude ADD (localizacao SDO_GEOMETRY);

-- Qualidade da coordenada, no mesmo padrão da acessibilidade (status, motivo e data).
-- Parte das coordenadas do CNES está errada (fora da cidade, longe do próprio bairro ou
-- num ponto genérico usado por unidades de bairros diferentes). O ETL marca essas como
-- SUSPEITA e, quando conseguir achar o endereço no OpenStreetMap, como CORRIGIDA.
ALTER TABLE unidade_saude ADD (
  status_coordenada            VARCHAR2(15)  DEFAULT 'NAO_VERIFICADO' NOT NULL,
  motivo_coordenada            VARCHAR2(200),
  data_verificacao_coordenada  DATE
);

ALTER TABLE unidade_saude ADD CONSTRAINT ck_unidade_status_coord
  CHECK (status_coordenada IN ('CONFIAVEL', 'SUSPEITA', 'CORRIGIDA', 'NAO_VERIFICADO'));

ALTER TABLE unidade_saude ADD CONSTRAINT ck_unidade_status_coord_motivo
  CHECK (status_coordenada = 'NAO_VERIFICADO'
      OR (motivo_coordenada IS NOT NULL AND data_verificacao_coordenada IS NOT NULL));

UPDATE unidade_saude
SET localizacao = SDO_GEOMETRY(2001, 4326, SDO_POINT_TYPE(longitude, latitude, NULL), NULL, NULL)
WHERE latitude IS NOT NULL AND longitude IS NOT NULL;

CREATE OR REPLACE TRIGGER trg_unidade_localizacao
BEFORE INSERT OR UPDATE OF latitude, longitude ON unidade_saude
FOR EACH ROW
BEGIN
  IF :NEW.latitude IS NOT NULL AND :NEW.longitude IS NOT NULL THEN
    :NEW.localizacao := SDO_GEOMETRY(2001, 4326, SDO_POINT_TYPE(:NEW.longitude, :NEW.latitude, NULL), NULL, NULL);
  ELSE
    :NEW.localizacao := NULL;
  END IF;
END;
/

CREATE OR REPLACE TRIGGER trg_parada_localizacao
